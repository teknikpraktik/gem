def write_phase2(root, catalog, status, access, results, blocked, group_windows, daily_results, daily_blocked,
                 agreement, impl, runs) -> None:
    gen = Path(root) / "reports" / "generated"
    L = ["# Phase 2 (generated)", "", "Generated by `python -m gem.research`. Do not edit by hand.", ""]

    # 1. access
    hosts: dict[str, list] = {}
    for a in access:
        hosts.setdefault(a["host"], []).append(a)
    L += ["## 1. Source access in this run", "", "| host | series | OK | failed | example error |", "|---|---:|---:|---:|---|"]
    for h, rows in sorted(hosts.items()):
        ok = sum(r["status"] == "OK" for r in rows)
        bad = [r for r in rows if r["status"] != "OK"]
        err = bad[0]["error"].replace("|", "/")[:120] if bad else ""
        L.append(f"| {h} | {len(rows)} | {ok} | {len(bad)} | {err} |")
    L += ["", "Failed endpoints:", ""]
    for a in access:
        if a["status"] != "OK":
            L.append(f"- `{a['series']}` → `{a['endpoint']}`")
    L.append("")

    # 2. Swedish data quality
    L += ["## 2. Swedish model data", "", "| Role | Series | Source | Period | Quality | TR status | Loaded |",
          "|---|---|---|---|---|---|---|"]
    for role, sid in SWEDISH_ROLES:
        e = catalog[sid]
        st = status.get(sid, {})
        tr = "TR index" if e["is_total_return"] else ("yield -> synthetic TR" if e["asset_class"] == "money_market_yield" else "n/a (FX)")
        L.append(f"| {role} | `{sid}` | {e['provider']} | {e['start_date']} → {e['end_date']} | {e['quality_status']} | "
                 f"{tr} | {st.get('status', 'not requested')} |")
    L.append("")

    # 3. groups
    L += ["## 3. Comparison groups (all members evaluated over the common window)", ""]
    for g, info in sorted(group_windows.items()):
        L.append(f"### {g}")
        L.append(f"- common window: {info['common_window'] or 'n/a (no Swedish member could run)'}")
        for m in info["members"]:
            if m in blocked:
                L.append(f"- `{m}`: **BLOCKED** – missing " + ", ".join(f"`{k}`" for k in blocked[m]["missing"]))
            else:
                L.append(f"- `{m}`: ran")
        if info["common_window"]:
            cw = f"COMMON_{g}"
            sel = [r for r in results if r.window == cw]
            L += ["", "| run | execution | cost bp/side | CAGR | vol | MDD | Sharpe | Sortino | Calmar | switches | turnover/yr | longest DD (m) | longest underperf. (m) |",
                  "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
            for r in sel:
                m = r.metrics
                L.append(f"| {r.run_spec.run_id} | {r.execution} | {r.cost_per_side_bps:g} | {_pct(m.get('cagr'))} | "
                         f"{_pct(m.get('volatility'))} | {_pct(m.get('max_drawdown'))} | {_num(m.get('sharpe'))} | "
                         f"{_num(m.get('sortino'))} | {_num(m.get('calmar'))} | {m.get('number_of_switches', 0)} | "
                         f"{_pct(m.get('annual_turnover'))} | {m.get('longest_drawdown_months')} | "
                         f"{m.get('longest_underperformance_vs_benchmark_months')} |")
        L.append("")

    # 4. agreement
    L += ["## 4. GEM_ORIGINAL vs GEM_SEK", ""]
    for k, v in agreement.items():
        L.append(f"### {k}")
        if v.get("status") != "OK":
            L.append(f"- **BLOCKED** – runs not available: {', '.join(v.get('missing_runs', []))}")
            L.append("")
            continue
        L += [f"- window: {v['window']} ({v['first_signal']} .. {v['last_signal']}), signal months: {v['months']}",
              f"- identical: {v['identical']}, different: {v['different']}, agreement: {_pct(v['agreement_pct'], 1)}",
              f"- differences concentrated in: {v['top_years']}  (by year: {v['differences_by_year']})",
              f"- transitions original->sek: {v['crosstab']}",
              f"- CAGR in SEK: original {_pct(v['original_in_sek']['cagr'])}, GEM_SEK {_pct(v['sek_model']['cagr'])}, "
              f"diff {_pct(v['cagr_diff_sek_minus_original'])}",
              f"- max DD in SEK: original {_pct(v['original_in_sek']['max_drawdown'])}, GEM_SEK "
              f"{_pct(v['sek_model']['max_drawdown'])}, diff {_pct(v['maxdd_diff_sek_minus_original'])}", ""]

    # 5. daily execution scenarios
    L += ["## 5. Execution scenarios on daily data (A published close / B next tradable / C conservative)", ""]
    if daily_results:
        L += ["| run | scenario | label | cost bp/side | CAGR | MDD | Sharpe | trades | avg bdays signal→exec | avg bdays out of market |",
              "|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for r in daily_results:
            m = r.metrics
            L.append(f"| {r.run_spec.run_id} | {r.scenario} | {r.label} | {r.cost:g} | {_pct(m.get('cagr'))} | "
                     f"{_pct(m.get('max_drawdown'))} | {_num(m.get('sharpe'))} | {m.get('number_of_trades')} | "
                     f"{_num(m.get('avg_bdays_signal_to_execution'))} | {_num(m.get('avg_bdays_out_of_market_per_switch'))} |")
    for k, miss in sorted(daily_blocked.items()):
        L.append(f"- `{k}` daily scenarios **BLOCKED** – missing " + ", ".join(f"`{m}`" for m in miss))
    L.append("")

    # 6. implementation gap
    L += ["## 6. Implementation gap: REGIONAL_SEK index signal vs Avanza funds", ""]
    if impl.get("status") != "OK":
        L.append(f"- **BLOCKED** – {impl.get('reason') or 'missing NAV: ' + ', '.join(impl.get('missing_nav', []))}")
    else:
        L += [f"- period from {impl['period_start']}",
              f"- index portfolio CAGR {_pct(impl['index_portfolio'].get('cagr'))}, MDD {_pct(impl['index_portfolio'].get('max_drawdown'))}",
              f"- fund portfolio CAGR {_pct(impl['fund_portfolio'].get('cagr'))}, MDD {_pct(impl['fund_portfolio'].get('max_drawdown'))}",
              f"- investable minus index CAGR: {_pct(impl['investable_minus_index_cagr'])}",
              f"- execution delay (bdays): index {_num(impl['execution_delay_bdays_index'])}, funds {_num(impl['execution_delay_bdays_fund'])}",
              f"- signal deviation (fund-NAV momentum vs index momentum): {impl['signal_deviation']}",
              f"- tracking difference: {impl['tracking_difference']}",
              f"- ongoing charges: {impl['ongoing_charges']}"]
    L.append("")
    (gen / "phase2.md").write_text("\n".join(L) + "\n")
    (gen / "phase2.json").write_text(json.dumps({
        "access": access, "group_windows": group_windows, "agreement": agreement, "implementation_gap": impl,
        "daily_blocked": daily_blocked,
        "daily_results": [{"run": r.run_spec.run_id, "scenario": r.scenario, "label": r.label, "cost": r.cost,
                           "metrics": r.metrics} for r in daily_results],
    }, indent=2, default=str, sort_keys=True))
