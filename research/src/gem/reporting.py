def _pct(x, d=2):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{100 * x:.{d}f}%"


def _num(x, d=2):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{x:.{d}f}"


def summary_frame(results) -> pd.DataFrame:
    rows = []
    for r in results:
        row = {"result_id": r.run_id, "run": r.run_spec.run_id, "strategy_id": r.strategy_id,
               "tier": r.data_tier, "window": r.window, "execution": r.execution,
               "lookahead_free": r.lookahead_free, "cost_per_side_bps": r.cost_per_side_bps,
               "stop_reason": r.stop_reason}
        row.update({k: r.metrics.get(k) for k in METRIC_COLS})
        rows.append(row)
    return pd.DataFrame(rows)


def _md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(cols))) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(out)


def write_all(root: Path, catalog, status, quality, xval, results, blocked, instruments) -> None:
    gen = root / "reports" / "generated"
    gen.mkdir(parents=True, exist_ok=True)

    # ---------------- series status & quality -----------------------------------
    st_rows = []
    for sid in sorted(status):
        e = catalog[sid]
        q = quality.get(sid, {})
        st_rows.append({
            "id": sid, "status": status[sid]["status"], "quality_status": e["quality_status"],
            "verification": e["verification"], "is_total_return": e["is_total_return"],
            "currency": e["currency"], "observed_first": q.get("month_end_first"),
            "observed_last": q.get("month_end_last"), "sha256": status[sid].get("sha256", "")[:16],
            "fetch": status[sid].get("fetch", ""), "error": status[sid].get("error", ""),
        })
    st = pd.DataFrame(st_rows)
    st.to_csv(gen / "series_status.csv", index=False)
    (gen / "data_quality.json").write_text(json.dumps({"status": status, "quality": quality,
                                                       "cross_validation": xval}, indent=2, default=str,
                                                      sort_keys=True))
    lines = ["# Data quality (generated)", "",
             "Generated by `python -m gem.research`. Do not edit by hand.", "",
             "## Series availability", "",
             _md_table(st[["id", "status", "quality_status", "verification", "observed_first", "observed_last",
                           "fetch", "sha256"]].fillna("")), "",
             "## Unavailable series and reason", ""]
    for _, r in st[st["status"] != "OK"].iterrows():
        lines.append(f"- `{r['id']}`: {r['error']}")
    lines += ["", "## Checks per loaded series", "",
              "| id | month-ends | first | last | stale month-ends | missing month-ends | extreme moves |",
              "|---|---:|---|---|---|---|---|"]
    for sid, q in sorted(quality.items()):
        st_list = q.get("stale_month_ends", [])
        mi = q.get("missing_month_ends", [])
        ext = q.get("extreme_moves", {})
        lines.append(f"| {sid} | {q.get('month_ends')} | {q.get('month_end_first')} | {q.get('month_end_last')} | "
                     f"{', '.join(st_list[:6]) or '-'}{' ...' if len(st_list) > 6 else ''} | "
                     f"{len(mi)} | {'; '.join(f'{k}: {v}' for k, v in list(ext.items())[:6]) or '-'}"
                     f"{' ...' if len(ext) > 6 else ''} |")
    lines += ["", "## Cross-source validation (monthly returns over overlap)", "",
              "| comparison | overlap | months | corr | mean abs diff | max abs diff (month) | TE ann. | CAGR a | CAGR b | CAGR diff |",
              "|---|---|---:|---:|---:|---|---:|---:|---:|---:|"]
    for x in xval:
        if x.get("overlap_months", 0) < 12:
            continue
        lines.append(
            f"| {x['label']} | {x['overlap']} | {x['overlap_months']} | {x['correlation']:.4f} | "
            f"{_pct(x['mean_abs_monthly_diff'], 3)} | {_pct(x['max_abs_monthly_diff'], 2)} ({x['max_abs_diff_month']}) | "
            f"{_pct(x['tracking_error_ann'])} | {_pct(x['cagr_a'])} | {_pct(x['cagr_b'])} | {_pct(x['cagr_diff'])} |")
    (gen / "data_quality.md").write_text("\n".join(lines) + "\n")

    # ---------------- backtest summary --------------------------------------------
    summ = summary_frame(results)
    summ.to_csv(gen / "summary.csv", index=False, float_format="%.6g")
    (gen / "summary.json").write_text(summ.to_json(orient="records", indent=2))
    lines = ["# Backtest results (generated)", "",
             "All runs x execution conventions x cost scenarios. `NEXT_MONTH_CLOSE` is the primary, "
             "look-ahead-free convention; `IDEALIZED_CLOSE` is shown only for comparison with published "
             "backtests (it trades at the close that defines the signal).", "",
             "Costs: `COST_0` = none, `COST_10BPS` = 10 bp per side on traded weight (a full switch costs 20 bp).", ""]
    show = ["window", "execution", "cost_per_side_bps", "start_date", "end_date", "cagr", "volatility",
            "max_drawdown", "sharpe", "sortino", "calmar", "number_of_switches", "annual_turnover",
            "average_holding_period_months", "longest_drawdown_months", "longest_drawdown_span",
            "longest_underperformance_vs_benchmark_months", "longest_underperformance_span", "best_year",
            "best_year_return", "worst_year",
            "worst_year_return", "end_value"]
    for run_id, g in summ.groupby("run", sort=True):
        lines += [f"## {run_id}", "", f"Tier: `{g['tier'].iloc[0]}`", ""]
        spec = next(r.run_spec for r in results if r.run_spec.run_id == run_id)
        for n in spec.notes:
            lines.append(f"- {n}")
        if g["stop_reason"].notna().any():
            lines.append(f"- stop: {g['stop_reason'].dropna().iloc[0]}")
        lines.append("")
        t = g[show].copy()
        for c in ("cagr", "volatility", "max_drawdown", "best_year_return", "worst_year_return", "annual_turnover"):
            t[c] = t[c].map(_pct)
        for c in ("sharpe", "sortino", "calmar", "average_holding_period_months"):
            t[c] = t[c].map(_num)
        t["end_value"] = t["end_value"].map(lambda v: f"{v:,.0f}" if pd.notna(v) else "n/a")
        lines += [_md_table(t.fillna("n/a")), ""]
    lines += ["## Blocked runs", "", "Runs that could not be executed because required series were unavailable. "
              "Nothing was substituted.", ""]
    for rid, b in sorted(blocked.items()):
        lines.append(f"### {rid} (`{b['tier']}`)")
        for m, err in b["missing"].items():
            lines.append(f"- `{m}`: {err}")
        lines.append("")
    (gen / "backtests.md").write_text("\n".join(lines) + "\n")
    (gen / "blocked_runs.json").write_text(json.dumps(blocked, indent=2, sort_keys=True))

    # ---------------- reproduction table --------------------------------------------
    rep = ["# Reproduction vs published GEM (generated)", "",
           f"Reference: {REFERENCE['source']} - {REFERENCE['verification']}.", ""]
    for rid in ("GEM_ORIGINAL_STRICT", "GEM_ORIGINAL_PROXY_3P"):
        sel = summ[(summ["run"] == rid) & (summ["window"] == "REF_1974_2013") & (summ["cost_per_side_bps"] == 0)]
        for _, r in sel.iterrows():
            rep += [f"## {rid} - {r['execution']} ({r['start_date']}..{r['end_date']})", "",
                    "| Metric | Reference | Our result | Difference |", "|---|---:|---:|---:|"]
            for k, f in (("cagr", _pct), ("volatility", _pct), ("max_drawdown", _pct), ("sharpe", _num)):
                ref, ours = REFERENCE[k], r[k]
                rep.append(f"| {k} | {f(ref)} | {f(ours)} | {f(ours - ref) if ref is not None else 'n/a'} |")
            rep.append(f"| number_of_switches | UNRESOLVED | {r['number_of_switches']} "
                       f"({_num(r['switches_per_year'])}/yr) | n/a |")
            rep.append("")
    (gen / "reproduction_table.md").write_text("\n".join(rep) + "\n")

    # ---------------- regime history for the main runs ------------------------------
    for r in results:
        if r.window == "FULL" and r.cost_per_side_bps == 0 and r.strategy_id.startswith("GEM"):
            m = r.monthly
            if m.empty:
                continue
            chg = m[m["target"] != m["target"].shift(1)][["signal_date", "target"]]
            chg.to_csv(gen / "runs" / r.run_id / "regime_changes.csv")


